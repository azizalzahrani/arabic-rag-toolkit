"""
مثال: معالجة الوثائق السعودية - Saudi Regulations Example

العربية:
    مثال عملي يوضح كيفية استخدام نظام RAG مع الوثائق والأنظمة السعودية

English:
    Practical example showing how to use RAG system with Saudi documents
"""

from arabic_rag.pipeline import ArabicRAGPipeline, PipelineConfig
from arabic_rag.chunker import ChunkingConfig
from arabic_rag.embeddings import EmbeddingConfig


def main():
    """
    الدالة الرئيسية - Main function

    العربية:
        مثال على استخدام نظام RAG مع وثائق سعودية حقيقية

    English:
        Example using RAG system with real Saudi documents
    """

    # إعداد التكوين المخصص
    print("إعداد نظام RAG للوثائق السعودية...")

    config = PipelineConfig(
        chunking_config=ChunkingConfig(
            chunk_size=400,
            chunk_overlap=100,
            split_on_sentences=True
        ),
        embedding_config=EmbeddingConfig(
            model_name="sentence-transformers/paraphrase-multilingual-MiniLM-L12-v2"
        ),
        verbose=True
    )

    pipeline = ArabicRAGPipeline(config=config)

    # وثائق سعودية نموذجية
    saudi_documents = [
        """
        نظام الشركات السعودي - المادة الأولى:
        الشركة التجارية هي عقد بمقتضاه يلتزم شخصان أو أكثر بأن يساهموا في مشروع مالي
        بتقديم حصص من مال أو عمل لاقتسام ما قد ينتج عنه من ربح أو خسارة.
        ويكون رأس مال الشركة المساهمة لا يقل عن خمسة ملايين ريال سعودي أو ما يعادله من
        العملات الأجنبية.
        """,

        """
        نظام الشركات السعودي - مجلس الإدارة:
        يتولى إدارة الشركة مجلس إدارة يتكون من ثلاثة أعضاء على الأقل وعشرة على الأكثر.
        يُنتخب أعضاء المجلس من المساهمين لمدة ثلاث سنوات.
        يكون كل عضو في مجلس الإدارة مسؤولاً تجاه الشركة والمساهمين عن تنفيذ مهامه
        بشكل صحيح وفقاً لأحكام النظام والقانون.
        """,

        """
        نظام الشركات السعودي - حقوق المساهمين:
        لكل مساهم الحق في حضور الجمعية العامة والتصويت على قراراتها.
        يحق للمساهمين الحصول على حصة من الأرباح بنسبة حصصهم.
        لهم الحق في الاطلاع على القوائم المالية والوثائق المتعلقة بأعمال الشركة.
        يحق لهم انتخاب أعضاء مجلس الإدارة واختيار المراقب الحسابي.
        """,

        """
        نظام الشركات السعودي - الجمعية العامة:
        تجتمع الجمعية العامة للمساهمين مرة واحدة في السنة على الأقل.
        تُقام الجمعية العامة العادية خلال أربعة أشهر من نهاية السنة المالية.
        يشترط لصحة انعقاد الجمعية العامة حضور المساهمين الذين يمثلون نصف رأس مال الشركة.
        ينظم نظام الشركات كيفية إجراء الجمعية العامة وصلاحياتها.
        """,

        """
        نظام الشركات السعودي - التقارير والقوائم المالية:
        يجب على الشركة إعداد قوائم مالية سنوية وفقاً للمعايير المحاسبية المقبولة.
        يجب فحص الحسابات من قبل مراقب حسابات مستقل معتمد.
        يتم عرض القوائم المالية والتقارير على الجمعية العامة للموافقة عليها.
        يتم نشر ملخص القوائم المالية في الجريدة وعلى موقع الشركة الإلكتروني.
        """,

        """
        نظام الشركات السعودي - توزيع الأرباح:
        لا يجوز توزيع أي جزء من أرباح السنة المالية إلا بعد تغطية الخسائر السابقة
        واستقطاع ما نصت عليه الأنظمة من احتياطيات.
        يتم تحديد نسبة توزيع الأرباح من قبل الجمعية العامة.
        يحق للمساهم الحصول على نصيبه من الأرباح الموزعة.
        """,
    ]

    print(f"تحميل {len(saudi_documents)} وثيقة سعودية...")
    pipeline.add_documents(saudi_documents)

    # أسئلة شائعة حول الأنظمة السعودية
    questions = [
        "ما هو الحد الأدنى لرأس مال الشركة المساهمة في السعودية؟",
        "كم عدد أعضاء مجلس الإدارة في الشركة المساهمة؟",
        "ما هي حقوق المساهمين الأساسية؟",
        "متى تجتمع الجمعية العامة للمساهمين؟",
        "من يتولى فحص الحسابات في الشركة المساهمة؟",
    ]

    print("\n" + "=" * 70)
    print("الاستعلامات عن الأنظمة السعودية")
    print("=" * 70)

    for i, question in enumerate(questions, 1):
        print(f"\n[السؤال {i}] {question}")
        print("-" * 70)

        result = pipeline.query_with_context(question, top_k=2)
        print(f"\nالإجابة:\n{result['answer'][:400]}...")
        print(f"\nعدد المستندات المستخدمة: {result['document_count']}")
        print(f"درجات التشابه: {[f'{s:.2f}' for s in result['similarity_scores']]}")

    # إحصائيات
    print("\n" + "=" * 70)
    print("إحصائيات النظام")
    print("=" * 70)
    stats = pipeline.get_pipeline_stats()
    print(f"عدد المستندات المحملة: {stats['total_documents']}")
    print(f"حجم متجه التضمين: {stats['embedding_dimension']}")
    print(f"نوع قاعدة البيانات: {stats['vector_store_type']}")


if __name__ == "__main__":
    main()
